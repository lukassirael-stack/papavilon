-- ── Týmy (jeden řádek = jedna vstupenka = jeden tým) ─────────────────
create table if not exists public.omg_tymy (
  id                 uuid primary key default gen_random_uuid(),
  vs                 bigint generated by default as identity (start with 26120001) unique,
  token              text not null unique default encode(gen_random_bytes(16), 'hex'),
  hra                text not null default 'vanocni-jizda-2026',
  email              text not null,
  castka             integer not null default 300,
  platba             text not null check (platba in ('stripe', 'prevod')),
  stav               text not null default 'ceka_platbu' check (stav in ('ceka_platbu', 'zaplaceno', 'zruseno')),
  zaplaceno_at       timestamptz,
  stripe_session_id  text,
  stripe_payment_intent text,
  nazev_tymu         text,
  pocet_hracu        integer,
  vek_hracu          text,
  registrovano_at    timestamptz,
  body               integer not null default 0,
  posledni_reseni_at timestamptz,
  souhlas            boolean not null default false,
  zdroj              text,
  poznamka           text,
  odkaz_odeslan_at   timestamptz,
  created_at         timestamptz not null default now()
);
comment on table public.omg_tymy is 'Outdoor Magic Games: vstupenky a týmy. Čteno jen přes service role. stav: ceka_platbu → zaplaceno (Stripe webhook nebo správa). Tým je zaregistrovaný, když má nazev_tymu.';

create unique index if not exists omg_tymy_nazev_unikatni
  on public.omg_tymy (hra, lower(nazev_tymu)) where nazev_tymu is not null;
create index if not exists omg_tymy_email on public.omg_tymy (lower(email));
create index if not exists omg_tymy_stripe_session on public.omg_tymy (stripe_session_id);

-- ── Kapitoly (adventní týdny) ────────────────────────────────────────
create table if not exists public.omg_kapitoly (
  id           serial primary key,
  hra          text not null default 'vanocni-jizda-2026',
  poradi       integer not null,
  nazev        text not null,
  podtitul     text,
  uvod         text,
  audio_url    text,
  otevreno_od  timestamptz not null,
  aktivni      boolean not null default true,
  unique (hra, poradi)
);
comment on table public.omg_kapitoly is 'Outdoor Magic Games: kapitoly hry (svíčky). Kapitola se hráčům otevře v otevreno_od.';

-- ── Stanoviště (úkoly v kapitole) ────────────────────────────────────
create table if not exists public.omg_stanoviste (
  id               serial primary key,
  kapitola_id      integer not null references public.omg_kapitoly (id) on delete cascade,
  poradi           integer not null default 1,
  typ              text not null default 'odpoved' check (typ in ('odpoved', 'info')),
  nazev            text not null,
  misto            text,
  zadani           text,
  napoveda         text,
  audio_url        text,
  obrazek_url      text,
  odpovedi         text[] not null default '{}',
  body             integer not null default 100,
  srazka_napoveda  integer not null default 20,
  aktivni          boolean not null default true,
  created_at       timestamptz not null default now()
);
comment on table public.omg_stanoviste is 'Outdoor Magic Games: úkoly v kapitole. odpovedi = seznam uznávaných odpovědí (porovnává se bez diakritiky a velikosti písmen). typ info = jen přečíst/poslechnout a pokračovat.';
create index if not exists omg_stanoviste_kapitola on public.omg_stanoviste (kapitola_id, poradi);

-- ── Postup týmu na stanovišti ────────────────────────────────────────
create table if not exists public.omg_pokrok (
  tym_id         uuid not null references public.omg_tymy (id) on delete cascade,
  stanoviste_id  integer not null references public.omg_stanoviste (id) on delete cascade,
  pokusy         integer not null default 0,
  napoveda_at    timestamptz,
  vyreseno_at    timestamptz,
  preskoceno     boolean not null default false,
  odpoved        text,
  body           integer not null default 0,
  primary key (tym_id, stanoviste_id)
);
comment on table public.omg_pokrok is 'Outdoor Magic Games: postup týmu na stanovišti. Řádek vzniká prvním pokusem nebo nápovědou, vyreseno_at se doplní po správné odpovědi.';

-- ── Log pokusů (pro analýzu a ochranu proti hádání) ──────────────────
create table if not exists public.omg_pokusy (
  id             bigserial primary key,
  tym_id         uuid not null references public.omg_tymy (id) on delete cascade,
  stanoviste_id  integer not null references public.omg_stanoviste (id) on delete cascade,
  odpoved        text,
  spravne        boolean not null,
  created_at     timestamptz not null default now()
);
create index if not exists omg_pokusy_tym on public.omg_pokusy (tym_id, stanoviste_id, created_at desc);

-- ── Body týmu se přepočítají po každé změně postupu ──────────────────
create or replace function public.omg_prepocitej_body() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_tym uuid;
begin
  v_tym := coalesce(new.tym_id, old.tym_id);
  update public.omg_tymy t set
    body = coalesce((select sum(p.body) from public.omg_pokrok p where p.tym_id = v_tym and p.vyreseno_at is not null), 0),
    posledni_reseni_at = (select max(p.vyreseno_at) from public.omg_pokrok p where p.tym_id = v_tym)
  where t.id = v_tym;
  return null;
end $$;

drop trigger if exists omg_pokrok_body on public.omg_pokrok;
create trigger omg_pokrok_body
  after insert or update or delete on public.omg_pokrok
  for each row execute function public.omg_prepocitej_body();

-- ── Veřejný žebříček (jen jméno týmu a body) ─────────────────────────
create or replace view public.omg_zebricek as
  select t.nazev_tymu, t.body, t.posledni_reseni_at,
         (select count(*) from public.omg_pokrok p where p.tym_id = t.id and p.vyreseno_at is not null) as vyreseno
  from public.omg_tymy t
  where t.stav = 'zaplaceno' and t.nazev_tymu is not null
  order by t.body desc, t.posledni_reseni_at asc nulls last, t.registrovano_at asc;

-- ── Zamknout pro veřejný klíč (čte jen server) ───────────────────────
alter table public.omg_tymy       enable row level security;
alter table public.omg_kapitoly   enable row level security;
alter table public.omg_stanoviste enable row level security;
alter table public.omg_pokrok     enable row level security;
